VALID_ACTIONS = ("follow_up", "no_action", "escalate")
VALID_STATUSES = (
    "applied",
    "screening",
    "oa",
    "interview",
    "offer",
    "accepted",
    "rejected",
    "withdrawn",
    "ghosted",
)


def case(
    *,
    id: str,
    company: str,
    role: str,
    status: str,
    days_applied: int,
    days_status: int,
    email_from: str,
    subject: str,
    snippet: str,
    action: str,
    family: str,
    rationale: str,
    diverge: bool,
    events: list | None = None,
    outreach: list | None = None,
    source: str = "direct",
) -> dict:
    assert status in VALID_STATUSES, status
    assert action in VALID_ACTIONS, action
    return {
        "id": id,
        "company": company,
        "role": role,
        "status": status,
        "source": source,
        "days_since_applied": days_applied,
        "days_since_status_update": days_status,
        "email_from": email_from,
        "email_subject": subject,
        "email_snippet": snippet,
        "events": events or [],
        "prior_outreach": outreach or [],
        "ground_truth_action": action,
        "ground_truth_should_follow_up": action == "follow_up",
        "family": family,
        "rationale": rationale,
        "expected_to_diverge": diverge,
    }


def ev(etype: str, title: str, days_ago: int, deadline_days: int | None = None, **data) -> dict:
    row: dict = {"type": etype, "title": title, "days_ago": days_ago, "data": data}
    if deadline_days is not None:
        row["deadline_days"] = deadline_days
    return row


def sent(days_ago: int, got_reply: bool = False, classification: str | None = None) -> dict:
    row: dict = {"days_ago": days_ago, "status": "sent", "got_reply": got_reply}
    if got_reply:
        row["reply_classification"] = classification or "neutral"
        row["days_to_reply"] = 1
    return row


